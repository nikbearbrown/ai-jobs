"""Which companies in companies.csv are named in the SEIS / COE student stories (books/seis/*/story.md)?

A mention is NOT a hire: a story can name a company the student interned at, studied, or merely used. Counts are a pointer
for a human, written to data/companies/seis-story-mentions.json. Case-sensitive whole-name match; names of 4 characters or
fewer count only when written in capitals (IBM, SAP, AMD), because 'Target', 'Gap', 'Box' and 'Block' are also words.

    python3 -m aijobs.story_mentions /path/to/books/seis
"""
import csv
import json
import re
import sys
from pathlib import Path

from .paths import COMPANIES, DATA

# Names that match ordinary words, headings or the school itself, not employers. 'Related' alone matched all 112 stories
# because every story has a 'Related' heading.
SKIP = {"Related", "Lambda", "Gemini", "Charles River", "Circle", "Current", "Northeastern University", "YouTube", "Wiley"}


def main(seis_dir):
    stories = {}
    for p in sorted(Path(seis_dir).glob("*/story.md")):
        stories[p.parent.name] = p.read_text(errors="ignore")
    rows = list(csv.DictReader(COMPANIES.open()))
    out = {}
    for r in rows:
        name = r["name"]
        if name in SKIP or (len(name) <= 4 and not name.isupper()):
            continue
        rx = re.compile(r"(?<![A-Za-z0-9])" + re.escape(name) + r"(?![A-Za-z0-9])")
        hit = [slug for slug, text in stories.items() if rx.search(text)]
        if hit:
            out[r["company_id"]] = {"name": name, "stories": len(hit), "story_slugs": hit[:12]}
    doc = {"_comment": "Mentions, not hires. Names of 4 chars or fewer count only in capitals. Generated by aijobs.story_mentions.",
           "stories_read": len(stories), "companies_mentioned": len(out),
           "companies": dict(sorted(out.items(), key=lambda kv: -kv[1]["stories"]))}
    (DATA / "companies" / "seis-story-mentions.json").write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")
    print(doc["stories_read"], "stories;", doc["companies_mentioned"], "companies mentioned")
    for cid, v in list(doc["companies"].items())[:40]:
        print(f"{v['stories']:3}  {v['name']}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "../seis")
