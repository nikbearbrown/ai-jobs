"""data/titles/titles.src.txt -> data/titles/titles.json

Adds, for families marked entry=y, the entry-level forms a board might use
(Junior X, Associate X, X I, X Intern, New Grad X) so a search does not miss them.
"""
import json
import re
import sys

from .paths import COURSES, TITLES, TITLES_SRC

ENTRY_PREFIXES = ["Junior", "Associate", "Entry Level", "Graduate", "Early Career", "New Grad"]
LEVEL_SKIP = re.compile(r"\b(Junior|Associate|Senior|Staff|Principal|Lead|Head|Director|VP|Chief|Intern|Manager|Entry|Graduate|New Grad|Early|I|II|Fellow|Resident)\b", re.I)


def parse(text):
    fams, cur = [], None
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("## "):
            key, label, courses, entry = [p.strip() for p in line[3:].split("|")]
            cur = {"key": key, "label": label, "courses": [c for c in courses.split(",") if c],
                   "entry_forms": entry.lower() == "y", "titles": []}
            fams.append(cur)
        elif line.startswith("#"):
            continue
        elif cur is not None:
            cur["titles"] += [t.strip() for t in line.split(";") if t.strip()]
    return fams


def entry_variants(title):
    if LEVEL_SKIP.search(title):
        return []
    out = [f"{p} {title}" for p in ENTRY_PREFIXES]
    out += [f"{title} I", f"{title} Intern", f"{title}, New Grad"]
    return out


def build(text, course_ids):
    """titles.src.txt text -> the titles.json document (pure: no file is read or written)."""
    fams = parse(text)
    seen, total_base, total_entry = {}, 0, 0
    for f in fams:
        bad = [c for c in f["courses"] if c not in course_ids]
        if bad:
            raise ValueError(f"{f['key']}: unknown course ids {bad}")
        uniq = []
        for t in f["titles"]:
            if t.lower() in seen:
                continue
            seen[t.lower()] = f["key"]
            uniq.append(t)
        f["titles"] = uniq
        f["entry_variants"] = []
        if f["entry_forms"]:
            for t in uniq:
                for v in entry_variants(t):
                    if v.lower() not in seen:
                        seen[v.lower()] = f["key"]
                        f["entry_variants"].append(v)
        total_base += len(uniq)
        total_entry += len(f["entry_variants"])
    return {
        "_comment": "Generated by python3 -m aijobs.build_titles from titles.src.txt. Edit the .src.txt, never this file. A title is a hypothesis about what a board calls a job; the collector measures which ones exist. First family that claims a title keeps it (dedupe is case-insensitive), so a title appears once.",
        "counts": {"families": len(fams), "titles": total_base, "entry_level_variants": total_entry},
        "families": fams,
    }


def render(doc):
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main():
    course_ids = {c["id"] for c in json.loads(COURSES.read_text())["courses"]}
    try:
        doc = build(TITLES_SRC.read_text(), course_ids)
    except ValueError as e:
        sys.exit(str(e))
    TITLES.write_text(render(doc))
    print(doc["counts"])


if __name__ == "__main__":
    main()
